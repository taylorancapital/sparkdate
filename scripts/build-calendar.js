#!/usr/bin/env node
/**
 * scripts/build-calendar.js
 *
 * Renders content/queue.csv as a readable 30-day calendar — every post in
 * date order with its full caption, hashtags and links, ready to paste into
 * Meta.
 *
 * This is the human-facing view of the queue. The CSV is the source of truth
 * and is what the linter and publishers read; nobody wants to plan a month by
 * scrolling a spreadsheet.
 *
 * Output is DERIVED. Never edit it and never keep versions of it — change
 * queue.csv and run this again. Storing copies is how the calendar ended up
 * as six near-identical spreadsheets in Downloads.
 *
 * Usage:
 *   node scripts/build-calendar.js --out=build/calendar.md
 */

'use strict';

const fs = require('fs');
const path = require('path');
const Q = require('../lib/content-queue');

const REPO = path.join(__dirname, '..');
const QUEUE = path.join(REPO, 'content', 'queue.csv');
const BRAND = path.join(REPO, 'content', 'brand.json');

const arg = (n, d) => {
  const hit = process.argv.find((a) => a.startsWith(`--${n}=`));
  return hit ? hit.split('=').slice(1).join('=') : d;
};

const longDate = (iso) => (/^\d{4}-\d{2}-\d{2}$/.test(iso || '')
  ? new Date(iso + 'T12:00:00Z').toLocaleDateString('en-US',
      { weekday: 'long', month: 'long', day: 'numeric', timeZone: 'UTC' })
  : iso);

function clockTime(t) {
  const m = /^(\d{2}):(\d{2})$/.exec(String(t || ''));
  if (!m) return t;
  let h = Number(m[1]);
  const ap = h >= 12 ? 'PM' : 'AM';
  h = h % 12 || 12;
  return `${h}:${m[2]} ${ap}`;
}

const platformLabel = (p) => String(p || '')
  .split(',').map((x) => x.trim())
  .map((x) => ({ ig: 'Instagram', fb: 'Facebook', ig_story: 'IG Story', tiktok: 'TikTok' }[x] || x))
  .join(' + ');

function main() {
  const brand = JSON.parse(fs.readFileSync(BRAND, 'utf8'));
  const { rows } = Q.parseCsv(fs.readFileSync(QUEUE, 'utf8'));

  const live = rows.filter((r) => r.state !== 'skipped')
    .sort((a, b) => (a.date + a.time).localeCompare(b.date + b.time));

  const O = [];
  const P = (s = '') => O.push(s);

  P('# SparkDate — 30-day content calendar');
  P('');
  P(`**${live.length} posts · ${live[0].date} to ${live[live.length - 1].date} · ${Object.keys(brand.events).length} events**`);
  P('');
  P('Generated from `content/queue.csv`. **Do not edit this file** — edit the');
  P('queue and rebuild, or your change is lost on the next run.');
  P('');
  P('| Event | When | Where | Price |');
  P('|---|---|---|---|');
  for (const [key, e] of Object.entries(brand.events)) {
    const p = e.pricing || {};
    const price = [p.early_bird ? `$${p.early_bird.toFixed(2)} early bird` : null,
      p.regular ? `$${p.regular.toFixed(2)}` : null].filter(Boolean).join(' → ');
    P(`| **${e.name}** \`${key}\` | ${longDate(e.date)} | ${e.venue}, ${e.city} | ${price} |`);
  }
  P('');
  P('---');

  let day = '';
  for (const r of live) {
    if (r.date !== day) { day = r.date; P(''); P(`## ${longDate(r.date)}`); P(''); }
    const ev = brand.events[Q.rowEvents(r)[0]] || {};
    const badge = r.state === 'posted' ? ' ✅ posted'
      : r.state === 'approved' ? ' 🟡 scheduled' : '';

    P(`### ${clockTime(r.time)} — ${ev.name || '?'}  \`${r.row_id}\`${badge}`);
    P('');
    P(`**${r.format}** · ${platformLabel(r.platforms)}`);
    P('');
    P('**Caption**');
    P('');
    P('```');
    P(String(r.caption).split('\r').join('').trim());
    P('```');
    P('');
    P('**Hashtags**');
    P('');
    P('```');
    P(r.hashtags);
    P('```');
    P('');
    if (r.link_fb) P(`- Facebook link: \`${r.link_fb}\``);
    if (r.link_ig) P(`- Instagram bio link: \`${r.link_ig}\``);
    P('');
    P(`- Artwork: ${r.asset_files ? `ready — ${r.asset_files}`
      : (/live capture|story frames/i.test(r.format) ? '📷 shot on the night' : '⬜ not made yet')}`);
    P('');
  }

  const text = O.join('\n');
  const dest = arg('out');
  if (dest) {
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.writeFileSync(dest, text, 'utf8');
    console.log(`wrote ${dest} — ${live.length} posts`);
  } else console.log(text);
}

if (require.main === module) main();
